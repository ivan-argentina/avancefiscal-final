CREATE OR REPLACE FUNCTION "public"."recalcular_saldo_factura"("p_idfactura" bigint) RETURNS "void"
    LANGUAGE "plpgsql"
    AS $$
declare
  v_total numeric(12,2);
  v_pagado numeric(12,2);
  v_saldo numeric(12,2);
  v_estado varchar(20);
begin
  select total
  into v_total
  from public.facturas
  where id = p_idfactura;

  if v_total is null then
    return;
  end if;

  select coalesce(sum(importe_aplicado), 0)
  into v_pagado
  from public.detalle_pagos_clientes
  where idfactura = p_idfactura;

  v_saldo := v_total - v_pagado;

  if v_saldo < 0 then
    v_saldo := 0;
  end if;

  if v_pagado <= 0 then
    v_estado := 'pendiente';
  elsif v_pagado < v_total then
    v_estado := 'parcial';
  else
    v_estado := 'pagada';
  end if;

  update public.facturas
  set
    saldo = v_saldo,
    estado_pago = v_estado
  where id = p_idfactura;
end;
$$;


ALTER FUNCTION "public"."recalcular_saldo_factura"("p_idfactura" bigint) OWNER TO "postgres";


CREATE OR REPLACE FUNCTION "public"."trg_recalcular_saldo_factura"() RETURNS "trigger"
    LANGUAGE "plpgsql"
    AS $$
begin
  if tg_op = 'DELETE' then
    perform public.recalcular_saldo_factura(old.idfactura);
    return old;
  else
    perform public.recalcular_saldo_factura(new.idfactura);
    return new;
  end if;
end;
$$;


