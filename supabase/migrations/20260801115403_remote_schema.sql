CREATE OR REPLACE FUNCTION "public"."descontar_stock_multiple"("items" "jsonb", "p_idempresa" "uuid") RETURNS "void"
    LANGUAGE "plpgsql"
    AS $$
declare
  item jsonb;
begin
  for item in
    select * from jsonb_array_elements(items)
  loop
    update articulos
    set stock = stock - (item->>'cantidad')::numeric
    where id = (item->>'idarticulo')::bigint
      and idempresa = p_idempresa;
  end loop;
end;
$$;


ALTER FUNCTION "public"."descontar_stock_multiple"("items" "jsonb", "p_idempresa" "uuid") OWNER TO "postgres";


